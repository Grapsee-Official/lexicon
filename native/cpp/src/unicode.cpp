bool is_combining_mark(char32_t cp) {
    // Combining Diacritical Marks: U+0300–U+036F
    // Combining Diacritical Marks Supplement: U+1DC0–U+1DFF
    // Combining Diacritical Marks for Symbols: U+20D0–U+20FF
    return (cp >= 0x0300 && cp <= 0x036F)
        || (cp >= 0x1DC0 && cp <= 0x1DFF)
        || (cp >= 0x20D0 && cp <= 0x20FF);
}

char32_t base_char(char32_t cp) {
    auto it = decomposition_table.find(cp);
    if (it != decomposition_table.end()) {
        return it->second.first; // base character
    }
    return cp;
}

std::string normalize_nfd(std::string_view input) {
    auto cps = utf8_to_utf32(input);
    std::u32string decomposed;

    // Recursive decomposition
    for (char32_t cp : cps) {
        auto it = decomposition_table.find(cp);
        if (it != decomposition_table.end()) {
            decomposed += it->second.first;
            decomposed += it->second.second;
        } else {
            decomposed += cp;
        }
    }

    // Canonical reordering of combining marks (simplified: stable sort by CCC)
    // Full implementation would use Canonical Combining Class data
    // For now, we keep the order as-is (most cases work fine)

    return utf32_to_utf8(decomposed);
}

std::string normalize_nfc(std::string_view input) {
    // NFC = NFD then canonical composition
    std::string nfd = normalize_nfd(input);
    auto cps = utf8_to_utf32(nfd);

    std::u32string composed;
    for (size_t i = 0; i < cps.size(); ++i) {
        char32_t base = cps[i];
        // Consume following combining marks and try to compose
        while (i + 1 < cps.size() && is_combining_mark(cps[i + 1])) {
            char32_t combiner = cps[i + 1];
            uint64_t key = (static_cast<uint64_t>(base) << 16) | combiner;
            auto it = composition_table.find(key);
            if (it != composition_table.end()) {
                base = it->second;
                ++i; // consumed the combiner
            } else {
                break; // no composition possible
            }
        }
        composed += base;
    }

    return utf32_to_utf8(composed);
}

bool is_nfc(std::string_view input) {
    return normalize_nfc(input) == std::string(input);
}

std::string casefold(std::string_view input) {
    auto cps = utf8_to_utf32(input);
    std::u32string folded;
    for (char32_t cp : cps) {
        // Simple ASCII casefold + common Latin
        if (cp >= 'A' && cp <= 'Z') cp += 32;
        else if (cp >= 0x00C0 && cp <= 0x00DE && cp != 0x00D7) cp += 32;
        else if (cp == 0x0130) cp = 0x0069; // Turkish İ → i
        folded += cp;
    }
    return utf32_to_utf8(folded);
}

std::string strip_diacritics(std::string_view input) {
    auto cps = utf8_to_utf32(input);
    std::u32string stripped;
    for (char32_t cp : cps) {
        if (!is_combining_mark(cp)) {
            // Also decompose precomposed chars and take base only
            char32_t base = base_char(cp);
            if (!is_combining_mark(base)) {
                stripped += base;
            }
        }
    }
    return utf32_to_utf8(stripped);
}

