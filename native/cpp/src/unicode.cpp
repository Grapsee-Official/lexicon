// UTF-8 decode
static int utf8_decode(const char* s, size_t len, size_t& i, char32_t& cp) {
    if (i >= len) return 0;
    unsigned char c = s[i];
    if (c < 0x80) { cp = c; i++; return 1; }
    if ((c & 0xE0) == 0xC0 && i+1 < len) {
        cp = ((c & 0x1F) << 6) | (static_cast<unsigned char>(s[i+1]) & 0x3F);
        i += 2; return 2;
    }
    if ((c & 0xF0) == 0xE0 && i+2 < len) {
        cp = ((c & 0x0F) << 12) | ((static_cast<unsigned char>(s[i+1]) & 0x3F) << 6)
           | (static_cast<unsigned char>(s[i+2]) & 0x3F);
        i += 3; return 3;
    }
    if ((c & 0xF8) == 0xF0 && i+3 < len) {
        cp = ((c & 0x07) << 18) | ((static_cast<unsigned char>(s[i+1]) & 0x3F) << 12)
           | ((static_cast<unsigned char>(s[i+2]) & 0x3F) << 6)
           | (static_cast<unsigned char>(s[i+3]) & 0x3F);
        i += 4; return 4;
    }
    cp = c; i++; return 1;
}

// UTF-8 encode
static void utf8_encode(char32_t cp, std::string& out) {
    if (cp < 0x80) {
        out += static_cast<char>(cp);
    } else if (cp < 0x800) {
        out += static_cast<char>(0xC0 | (cp >> 6));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    } else if (cp < 0x10000) {
        out += static_cast<char>(0xE0 | (cp >> 12));
        out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    } else {
        out += static_cast<char>(0xF0 | (cp >> 18));
        out += static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
        out += static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (cp & 0x3F));
    }
}

std::u32string utf8_to_utf32(std::string_view s) {
    std::u32string result;
    size_t i = 0;
    char32_t cp;
    while (utf8_decode(s.data(), s.size(), i, cp) > 0) {
        result += cp;
    }
    return result;
}

std::string utf32_to_utf8(const std::u32string& s) {
    std::string result;
    for (char32_t cp : s) {
        utf8_encode(cp, result);
    }
    return result;
}

